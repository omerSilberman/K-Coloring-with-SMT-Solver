"""
Precomputes, for every K up to a limit, the shortest string that has exactly K
distinct substrings (the empty string included), and writes them to
substring_strings.txt. Used by the STR-SUB theory in smt_solver_cvc5.

Usage: python3 gen_substring_strings.py [MAX_K] [OUTPUT_FILE]
"""
import sys
import string

ALPHABET = string.ascii_lowercase

def count_distinct_substrings(s):
    # +1 for the empty string
    return len({s[i:j] for i in range(len(s)) for j in range(i + 1, len(s) + 1)}) + 1

def canonical_strings(length):
    """Yields strings of the given length in lexicographic order, where each new
    letter is the next unused one ('a', then 'b', ...). Renaming letters does not
    change the substring count, so this covers every string up to renaming."""
    def extend(prefix, used):
        if len(prefix) == length:
            yield prefix
            return
        for c in range(min(used + 1, len(ALPHABET))):
            yield from extend(prefix + ALPHABET[c], max(used, c + 1))
    yield from extend("", 0)

def shortest_strings(max_k):
    """Maps every K in 1..max_k to the shortest (then lexicographically smallest)
    string with exactly K distinct substrings."""
    found = {}
    length = 0
    while len(found) < max_k:
        for s in canonical_strings(length):
            k = count_distinct_substrings(s)
            if k <= max_k and k not in found:
                found[k] = s
        length += 1
    return found

if __name__ == "__main__":
    max_k = int(sys.argv[1]) if len(sys.argv) > 1 else 20
    output_file = sys.argv[2] if len(sys.argv) > 2 else "substring_strings.txt"

    found = shortest_strings(max_k)
    with open(output_file, "w") as f:
        f.write("# K string: shortest string with exactly K distinct substrings (empty string included)\n")
        f.write("# Generated by gen_substring_strings.py\n")
        for k in range(1, max_k + 1):
            f.write(f"{k} {found[k]}\n")
    print(f"Wrote strings for K=1..{max_k} to {output_file}")
